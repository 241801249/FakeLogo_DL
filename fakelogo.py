import os
import pandas as pd

BASE_PATH = "/content/drive/MyDrive/archive (2)"
CSV_PATH = os.path.join(BASE_PATH, "file_mapping.csv")

df = pd.read_csv(CSV_PATH)
df.columns = df.columns.str.strip()

def resolve_image_path(filename):
    filename = str(filename).strip()
    filename = filename.replace("\\\\", "/").replace("\\", "/")
    return os.path.join(BASE_PATH, filename)

df["image_path"] = df["Filename"].apply(resolve_image_path)

df["exists"] = df["image_path"].apply(os.path.isfile)

print("CSV rows:", len(df))
print("Images found:", df["exists"].sum())
print("Missing images:", (~df["exists"]).sum())

df = df[df["exists"]].copy()

df["Label"] = df["Label"].astype(str).str.strip().str.lower()
df = df[df["Label"].isin(["genuine", "fake"])].copy()

df["label_id"] = df["Label"].map({
    "genuine": 0,
    "fake": 1
})

df = df.drop_duplicates(subset=["image_path"])

print("\nFinal usable images:", len(df))
print(df["Label"].value_counts())
display(df.head())

from sklearn.model_selection import train_test_split

SEED = 42

train_df, temp_df = train_test_split(
    df,
    test_size=0.30,
    random_state=SEED,
    stratify=df["label_id"]
)

val_df, test_df = train_test_split(
    temp_df,
    test_size=0.50,
    random_state=SEED,
    stratify=temp_df["label_id"]
)

print("Training:", len(train_df))
print("Validation:", len(val_df))
print("Testing:", len(test_df))

print("\nTraining labels:")
